// Hitch finder at the curl: real-time loop, the first jet hop at the ramp start in any build (e.g. /v1.3/), logs frames over 40 ms. node hitch2.mjs [path]
import {createRequire} from 'node:module';
const require = createRequire('/Users/jurek/openclaw/node_modules/');
const {chromium} = require('playwright-core');
const path = process.argv[2] || '/';
const b = await chromium.launch({executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist', '--disable-gpu-vsync', '--disable-frame-rate-limit']});
const p = await b.newPage({viewport: {width: 1440, height: 900}, deviceScaleFactor: 2});
p.on('pageerror', (e) => console.log('err', e.message));
p.on('console', (m) => { if (/warn|error/.test(m.type())) console.log('console', m.text().slice(0, 200)); });
p.on('requestfailed', (r) => console.log('failed', r.url().slice(0, 120)));
await p.goto('http://127.0.0.1:8840' + path + '?fixscale');
await p.waitForFunction(() => window.__rj && window.__rj.ready, null, {timeout: 120000});
await p.evaluate(() => { const R = window.__rj; window.__rjTest = true; R.play(); R.board(); window.__long = [];
  let last = performance.now(); const tick = (t) => { const d = t - last; last = t; if (d > 40) window.__long.push([+d.toFixed(0), window.__rj.state().mode]); requestAnimationFrame(tick); }; requestAnimationFrame(tick); });
await new Promise((r) => setTimeout(r, 3000));
await p.evaluate(() => { window.__long.push('hop'); window.__rj.input({lift: true}); });
await new Promise((r) => setTimeout(r, 600));
await p.evaluate(() => window.__rj.input({}));
await new Promise((r) => setTimeout(r, 2500));
console.log(path, JSON.stringify(await p.evaluate(() => window.__long)));
await b.close();
